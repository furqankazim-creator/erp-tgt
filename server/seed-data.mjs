function stamp(daysAgo) {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() - daysAgo);
  return d.toISOString();
}

function withTimestamps(row, index) {
  const created = stamp(index * 2);
  return { created_at: created, updated_at: created, ...row };
}

