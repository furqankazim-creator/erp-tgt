function buildWorkLogs() {
  const rows = [];
  let idx = 0;
  for (const person of WORK_LOG_ROSTER) {
    WORK_DAYS.forEach((date, dayIdx) => {
      // Deliberate gaps so the recommendations engine has real signal to surface.
      if (person.name === "Yuki Tanaka" && date === TODAY) return;
      if (person.name === "Priya Nair" && dayIdx === WORK_DAYS.length - 3) return;

      const project = person.projects[dayIdx % person.projects.length];
      const hours = person.base - (dayIdx % 3 === 0 ? 1 : 0);
      const blocker = person.name === "Daniel Kim" && date === TODAY;
      idx += 1;
      rows.push({
        id: `wl-${idx}`,
        employee: person.name,
        project_id: PROJECT_IDS[project],
        task_id: null,
        date,
        hours,
        notes: blocker ? "Blocked on staging environment access." : "Regular progress.",
        blocker,
        blocker_note: blocker ? "Needs DevOps to restore staging access." : null,
        created_at: `${date}T18:00:00.000Z`,
        updated_at: `${date}T18:00:00.000Z`,
      });
    });
  }
  return rows;
}

/** Deterministic pseudo-random 40-char hex string, so seed data stays stable across runs. */
function fakeSha(seed) {
  let h = seed >>> 0;
  let hex = "";
  for (let i = 0; i < 5; i++) {
    h = (Math.imul(h, 1103515245) + 12345) >>> 0;
    hex += h.toString(16).padStart(8, "0");
  }
  return hex.slice(0, 40);
}

